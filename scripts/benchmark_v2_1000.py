def test_prompt(prompt, category, idx, total):
    """Send a prompt to the API and return results."""
    start = time.time()
    try:
        resp = requests.post(API_URL, json={
            "model": MODEL,
            "messages": [{"role": "user", "content": prompt}],
            "temperature": 0.1,
            "max_tokens": 512,
        }, timeout=180)
        elapsed = time.time() - start
        data = resp.json()

        if "choices" not in data:
            return {
                "category": category, "index": idx, "prompt": prompt[:100],
                "status": "error", "error": str(data), "latency_sec": round(elapsed, 2),
            }

        content = data["choices"][0]["message"]["content"]
        usage = data.get("usage", {})
        return {
            "category": category, "index": idx,
            "prompt": prompt[:120],
            "response_length": len(content),
            "latency_sec": round(elapsed, 2),
            "prompt_tokens": usage.get("prompt_tokens", 0),
            "completion_tokens": usage.get("completion_tokens", 0),
            "has_code": "```" in content,
            "response_preview": content[:300],
            "full_response": content,
            "status": "ok",
        }
    except Exception as e:
        return {
            "category": category, "index": idx, "prompt": prompt[:100],
            "status": "error", "error": str(e), "latency_sec": round(time.time() - start, 2),
        }

def main():
    results = []
    total = sum(len(v) for v in TEST_PROMPTS.values())
    done = 0

    print(f"NexiFuse v2 Benchmark — {total} prompts across {len(TEST_PROMPTS)} categories")
    print(f"{'='*70}")

    for category, prompts in TEST_PROMPTS.items():
        print(f"\n=== {category} ({len(prompts)} prompts) ===")
        for i, prompt in enumerate(prompts):
            done += 1
            result = test_prompt(prompt, category, i, total)
            results.append(result)
            status = "OK" if result["status"] == "ok" else "ERR"
            latency = result.get("latency_sec", 0)
            length = result.get("response_length", 0)
            if done % 10 == 0 or result["status"] != "ok":
                print(f"  [{done}/{total}] {status} {latency:.1f}s {length} chars — {prompt[:55]}...")

    # Save raw results
    output_path = Path("data/benchmark_v2_1000_results.json")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w") as f:
        json.dump(results, f, indent=2)

    # Summary
    ok = [r for r in results if r["status"] == "ok"]
    err = [r for r in results if r["status"] != "ok"]

    print(f"\n{'='*70}")
    print(f"BENCHMARK COMPLETE: {len(ok)}/{total} passed, {len(err)} errors")
    print(f"{'='*70}")

    if ok:
        avg_latency = sum(r["latency_sec"] for r in ok) / len(ok)
        avg_length = sum(r["response_length"] for r in ok) / len(ok)
        avg_tokens = sum(r["completion_tokens"] for r in ok) / len(ok)
        code_pct = sum(1 for r in ok if r["has_code"]) / len(ok) * 100

        print(f"Avg latency:  {avg_latency:.2f}s")
        print(f"Avg response: {avg_length:.0f} chars / {avg_tokens:.0f} tokens")
        print(f"Code blocks:  {code_pct:.0f}%")
        print(f"\nPer-category breakdown:")
        for cat in TEST_PROMPTS:
            cat_results = [r for r in ok if r["category"] == cat]
            cat_err = [r for r in err if r["category"] == cat]
            if cat_results:
                cat_lat = sum(r["latency_sec"] for r in cat_results) / len(cat_results)
                cat_len = sum(r["response_length"] for r in cat_results) / len(cat_results)
                cat_code = sum(1 for r in cat_results if r["has_code"]) / len(cat_results) * 100
                print(f"  {cat:30s} {len(cat_results):>3}/{len(cat_results)+len(cat_err):>3} ok  lat={cat_lat:.1f}s  len={cat_len:.0f}  code={cat_code:.0f}%")

    print(f"\nResults saved to {output_path}")

if __name__ == "__main__":
    main()
